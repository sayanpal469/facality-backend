import mongoose from 'mongoose'
import { PRIORITY_VALUES, WORK_ORDER_STATUS, WORK_ORDER_STATUS_VALUES } from '../constants/enums.js'

const { Schema } = mongoose

const workOrderUpdateSchema = new Schema(
  {
    authorId: { type: Schema.Types.ObjectId, ref: 'User', required: true },
    note: { type: String, required: true, trim: true },
  },
  { timestamps: { createdAt: true, updatedAt: false } },
)

const workOrderSchema = new Schema(
  {
    enterpriseId: { type: Schema.Types.ObjectId, ref: 'Enterprise', required: true, index: true },
    code: { type: String, required: true, trim: true }, // e.g. "WO-10245" — human-friendly, unique per enterprise

    clientId: { type: Schema.Types.ObjectId, ref: 'Client', required: true, index: true },
    siteId: { type: Schema.Types.ObjectId, ref: 'Site', required: true, index: true },
    serviceId: { type: Schema.Types.ObjectId, ref: 'ServiceType', required: true },

    title: { type: String, required: true, trim: true },
    description: { type: String, trim: true, default: '' },
    priority: { type: String, enum: PRIORITY_VALUES, default: 'normal' },
    status: { type: String, enum: WORK_ORDER_STATUS_VALUES, default: WORK_ORDER_STATUS.CREATED, index: true },
    progress: { type: Number, min: 0, max: 100, default: 0 },

    assignedEmployeeId: { type: Schema.Types.ObjectId, ref: 'Employee', default: null },
    supervisorId: { type: Schema.Types.ObjectId, ref: 'Employee', default: null },

    startDate: { type: Date, default: null },
    dueDate: { type: Date, required: true },

    fromComplaintId: { type: Schema.Types.ObjectId, ref: 'Complaint', default: null },
    assetId: { type: Schema.Types.ObjectId, ref: 'Asset', default: null, index: true }, // the equipment being serviced
    pmScheduleId: { type: Schema.Types.ObjectId, ref: 'PmSchedule', default: null, index: true }, // generated by preventive maintenance
    // Set once the overdue sweep has alerted about this work order; cleared when the due date moves.
    overdueAlertedAt: { type: Date, default: null },

    updates: [workOrderUpdateSchema],

    // Every status transition (normal progression, override, cancel, client
    // approval) — the source for the client app's work order timeline.
    statusHistory: [
      {
        status: { type: String, enum: WORK_ORDER_STATUS_VALUES, required: true },
        progress: { type: Number, default: null },
        note: { type: String, default: null },
        actorId: { type: Schema.Types.ObjectId, ref: 'User', default: null },
        at: { type: Date, default: Date.now },
      },
    ],

    cancelReason: { type: String, default: null },
    overrideHistory: [
      {
        fromStatus: String,
        toStatus: String,
        reason: String,
        actorId: { type: Schema.Types.ObjectId, ref: 'User' },
        at: { type: Date, default: Date.now },
      },
    ],
  },
  { timestamps: true },
)

workOrderSchema.index({ enterpriseId: 1, code: 1 }, { unique: true })
workOrderSchema.index({ enterpriseId: 1, status: 1 })
workOrderSchema.index({ enterpriseId: 1, clientId: 1 })
workOrderSchema.index({ enterpriseId: 1, siteId: 1 })
workOrderSchema.index({ enterpriseId: 1, assignedEmployeeId: 1 })
workOrderSchema.index({ enterpriseId: 1, dueDate: 1 })

workOrderSchema.pre('save', function resetOverdueAlert() {
  if (!this.isNew && this.isModified('dueDate')) this.overdueAlertedAt = null
})

export const WorkOrder = mongoose.model('WorkOrder', workOrderSchema)
